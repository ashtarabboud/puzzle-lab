/* Five-letter word lists for Word Grid and Word Count (from SCOWL size tiers via wordlist-english).
   answers: t1 (most common), t2, t3 — plurals, past tenses and offensive words removed.
   guesses: every five-letter word in the game dictionary plus all answers. Output: src/data/five.js */
const w = require('wordlist-english'), fs = require('fs');
const five = lv => new Set([...w['english/' + lv], ...(w['english/american/' + lv] || [])].filter(x => /^[a-z]{5}$/.test(x)));
const t10 = five('10'), t20 = five('20'), t35 = five('35'), t40 = five('40'), t50 = five('50');
const all = new Set([...t10, ...t20, ...t35, ...t40, ...t50]);
const any = new Set(['10', '20', '35', '40', '50', '55', '60'].flatMap(lv => [...w['english/' + lv], ...(w['english/american/' + lv] || [])]));
const block = new Set('bitch boobs booty butts crack cunts dicks dildo dykes fucks gooks horny kikes nazis negro penis pimps porno prick pubes pussy queer rapes semen shits sluts spick titty turds twats whore wanks bimbo hooker lesbo homos japs gypsy'.split(' '));
function inflected(x) {
  if (/s$/.test(x) && !/ss$/.test(x) && (any.has(x.slice(0, -1)) || (/es$/.test(x) && any.has(x.slice(0, -2))))) return true;
  if (/ed$/.test(x) && (any.has(x.slice(0, -2)) || any.has(x.slice(0, -1)))) return true;
  if (/er$/.test(x) && any.has(x.slice(0, -2)) && x.slice(0, -2).length === 3 && /[aeiou]/.test(x[1]) === false) return false;
  return false;
}
const ok = x => !block.has(x) && !inflected(x);
const T1 = [...t10].filter(ok).sort(), T2 = [...t20].filter(x => !t10.has(x)).filter(ok).sort(), T3 = [...t35].filter(x => !t10.has(x) && !t20.has(x)).filter(ok).filter(x => !(/(er|ly)$/.test(x) && any.has(x.slice(0, -2)))).sort();
const guesses = [...all].filter(x => !block.has(x)).sort();
const out = '/* Generated by tools/build-five.js from SCOWL (wordlist-english). */\nPL.data.five=' + JSON.stringify({ t1: T1.join(''), t2: T2.join(''), t3: T3.join(''), g: guesses.join('') }) + ';\n';
fs.writeFileSync('src/data/five.js', out);
console.log('t1', T1.length, 't2', T2.length, 't3', T3.length, 'guesses', guesses.length, (out.length / 1024).toFixed(0) + 'KB');
